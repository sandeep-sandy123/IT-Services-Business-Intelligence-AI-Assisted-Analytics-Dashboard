--Q10. Find the top 5 clients by revenue.
WITH ClientRevenue AS
(
    SELECT
        c.ClientID,
        c.ClientName,
        SUM(p.ContractValue) AS Total_Revenue
    FROM Projects p
    JOIN Client c
        ON p.ClientID = c.ClientID
    GROUP BY c.ClientID, c.ClientName
)
SELECT TOP 5
    ClientName,
    Total_Revenue
FROM ClientRevenue
ORDER BY Total_Revenue DESC;

--Q11. Rank services by revenue.
SELECT
    s.ServiceName,
    SUM(p.ContractValue) AS Total_Revenue,
    RANK() OVER (
        ORDER BY SUM(p.ContractValue) DESC
    ) AS Revenue_Rank
FROM Projects p
JOIN Services s
    ON p.ServiceID = s.ServiceID
GROUP BY s.ServiceName;


--Q12. Find budget variance for every project.
SELECT
    ProjectID,
    ProjectName,
    BudgetCost,
    ActualCost,
    ActualCost - BudgetCost AS Variance,
    CASE
        WHEN ActualCost > BudgetCost THEN 'Over Budget'
        WHEN ActualCost < BudgetCost THEN 'Under Budget'
        ELSE 'On Budget'
    END AS Budget_Status
FROM Projects;

-- Q13. Find the highest-value project for each service.
WITH RankedProjects AS
(
    SELECT
        p.ProjectID,
        p.ProjectName,
        s.ServiceName,
        p.ContractValue,
        ROW_NUMBER() OVER (
            PARTITION BY p.ServiceID
            ORDER BY p.ContractValue DESC
        ) AS rn
    FROM Projects p
    JOIN Services s
        ON p.ServiceID = s.ServiceID
)
SELECT
    ProjectID,
    ProjectName,
    ServiceName,
    ContractValue
FROM RankedProjects
WHERE rn = 1;

