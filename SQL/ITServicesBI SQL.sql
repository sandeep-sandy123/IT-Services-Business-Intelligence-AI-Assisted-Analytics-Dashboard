-- Q6. Rank services by revenue.
SELECT
    s.ServiceName,
    SUM(p.ContractValue) AS Total_Revenue,
    RANK() OVER (
        ORDER BY SUM(p.ContractValue) DESC
    ) AS Revenue_Rank
FROM Projects p
