-- Q7.  Projects by Client
SELECT
    c.ClientName,
    COUNT(p.ProjectID) AS Total_Projects
FROM Client c
INNER JOIN Projects p
    ON c.ClientID = p.ClientID
GROUP BY
    c.ClientID,
    c.ClientName
ORDER BY Total_Projects DESC;

--Q8.  Client Revenue
SELECT
    c.ClientName,
    COUNT(p.ProjectID) AS Total_Projects,
    SUM(p.ContractValue) AS Total_Revenue
FROM Client c
INNER JOIN Projects p
    ON c.ClientID = p.ClientID
GROUP BY
    c.ClientID,
    c.ClientName
ORDER BY Total_Revenue DESC;

-- Q9. Employee Utilization
SELECT
    e.EmployeeID,
    e.EmployeeName,
    SUM(pa.BillableHours) AS Billable_Hours,
    SUM(pa.WorkedHours) AS Worked_Hours,
    CAST(
        SUM(pa.BillableHours) * 100.0 /
        NULLIF(SUM(pa.WorkedHours), 0)
        AS DECIMAL(10,2)
    ) AS Utilization_Percentage
FROM Employees e
INNER JOIN Project_Assignments pa
    ON e.EmployeeID = pa.EmployeeID
GROUP BY
    e.EmployeeID,
    e.EmployeeName
ORDER BY Utilization_Percentage DESC;

