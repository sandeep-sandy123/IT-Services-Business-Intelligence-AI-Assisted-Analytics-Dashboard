-- Q1. What is the total project value?
SELECT 
    SUM(ContractValue) AS Total_Project_Value
FROM Projects;

-- Q2. How many projects are there by status?
SELECT
    Status,
    COUNT(*) AS Total_Projects
FROM Projects
GROUP BY Status
ORDER BY Total_Projects DESC;

-- Q3. What is the revenue generated by each service?
SELECT
    s.ServiceName,
    SUM(p.ContractValue) AS Total_Revenue
FROM Projects p
JOIN Services s
    ON p.ServiceID = s.ServiceID
GROUP BY s.ServiceName
ORDER BY Total_Revenue DESC;

-- Q4. What is the budget vs actual cost for projects?
SELECT
    SUM(BudgetCost) AS Total_Budget,
    SUM(ActualCost) AS Total_Actual_Cost,
    SUM(ActualCost) - SUM(BudgetCost) AS Cost_Variance
FROM Projects;

-- Q5.What is the average customer satisfaction?
SELECT
    AVG(CAST(Satisfaction_Rating AS DECIMAL(10,2))) AS Avg_Satisfaction
FROM Customer_Feedback;

